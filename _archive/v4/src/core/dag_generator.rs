#[cfg(test)]
mod tests {
    use super::*;

    fn make_test_task(id: &str, deps: Vec<&str>) -> GeneratedTask {
        GeneratedTask {
            id: id.to_string(),
            description: format!("Task {}", id),
            dependencies: deps.into_iter().map(String::from).collect(),
            task_type: TaskType::Implement,
            priority: Priority::Normal,
            complexity: Complexity::Medium,
            skill_hint: None,
        }
    }

    #[test]
    fn test_parse_task_list_valid_json() {
        let json = r#"[
            {
                "id": "T1",
                "description": "Research API",
                "dependencies": [],
                "task_type": "research",
                "priority": "High",
                "complexity": "Simple",
                "skill_hint": null
            },
            {
                "id": "T2",
                "description": "Implement connector",
                "dependencies": ["T1"],
                "task_type": "implement",
                "priority": "Normal",
                "complexity": "Medium",
                "skill_hint": "rust-implementer"
            }
        ]"#;

        let tasks = parse_task_list(json).unwrap();
        assert_eq!(tasks.len(), 2);
        assert_eq!(tasks[0].id, "T1");
        assert_eq!(tasks[1].id, "T2");
        assert_eq!(tasks[1].dependencies, vec!["T1"]);
    }

    #[test]
    fn test_parse_task_list_with_code_fences() {
        let markdown = r#"```json
[
    {
        "id": "T1",
        "description": "First task",
        "dependencies": [],
        "task_type": "research",
        "priority": "Normal",
        "complexity": "Simple",
        "skill_hint": null
    }
]
```"#;

        let tasks = parse_task_list(markdown).unwrap();
        assert_eq!(tasks.len(), 1);
        assert_eq!(tasks[0].id, "T1");
    }

    #[test]
    fn test_parse_task_list_empty_array() {
        let json = "[]";
        let result = parse_task_list(json);
        assert!(matches!(result, Err(DagGenError::EmptyTaskList)));
    }

    #[test]
    fn test_validate_dag_valid() {
        let tasks = vec![
            make_test_task("T1", vec![]),
            make_test_task("T2", vec!["T1"]),
            make_test_task("T3", vec!["T2"]),
        ];

        assert!(validate_dag(&tasks).is_ok());
    }

    #[test]
    fn test_validate_dag_duplicate_ids() {
        let tasks = vec![
            make_test_task("T1", vec![]),
            make_test_task("T1", vec![]), // Duplicate!
        ];

        let result = validate_dag(&tasks);
        assert!(matches!(result, Err(DagGenError::InvalidDag(_))));
        if let Err(DagGenError::InvalidDag(msg)) = result {
            assert!(msg.contains("Duplicate"));
        }
    }

    #[test]
    fn test_validate_dag_cycle() {
        let tasks = vec![
            GeneratedTask {
                id: "T1".to_string(),
                description: "First".to_string(),
                dependencies: vec!["T2".to_string()], // T1 depends on T2
                task_type: TaskType::Implement,
                priority: Priority::Normal,
                complexity: Complexity::Medium,
                skill_hint: None,
            },
            GeneratedTask {
                id: "T2".to_string(),
                description: "Second".to_string(),
                dependencies: vec!["T1".to_string()], // T2 depends on T1 -> cycle!
                task_type: TaskType::Implement,
                priority: Priority::Normal,
                complexity: Complexity::Medium,
                skill_hint: None,
            },
        ];

        let result = validate_dag(&tasks);
        assert!(matches!(result, Err(DagGenError::InvalidDag(_))));
        if let Err(DagGenError::InvalidDag(msg)) = result {
            assert!(msg.contains("Cycle"));
        }
    }

    #[test]
    fn test_validate_dag_missing_dep() {
        let tasks = vec![
            make_test_task("T1", vec!["T999"]), // T999 doesn't exist
        ];

        let result = validate_dag(&tasks);
        assert!(matches!(result, Err(DagGenError::InvalidDag(_))));
        if let Err(DagGenError::InvalidDag(msg)) = result {
            assert!(msg.contains("non-existent"));
        }
    }

    #[test]
    fn test_parse_task_list_wrapper_object() {
        let json = r#"{"tasks": [
            {
                "id": "T1",
                "description": "Research API",
                "dependencies": [],
                "task_type": "research",
                "priority": "Normal",
                "complexity": "Simple",
                "skill_hint": null
            },
            {
                "id": "T2",
                "description": "Implement",
                "dependencies": ["T1"],
                "task_type": "implement",
                "priority": "Normal",
                "complexity": "Medium",
                "skill_hint": null
            }
        ]}"#;

        let tasks = parse_task_list(json).unwrap();
        assert_eq!(tasks.len(), 2);
        assert_eq!(tasks[0].id, "T1");
        assert_eq!(tasks[1].dependencies, vec!["T1"]);
    }

    #[test]
    fn test_validate_dag_self_reference() {
        let tasks = vec![
            GeneratedTask {
                id: "T1".to_string(),
                description: "Task".to_string(),
                dependencies: vec!["T1".to_string()], // Self-reference!
                task_type: TaskType::Implement,
                priority: Priority::Normal,
                complexity: Complexity::Medium,
                skill_hint: None,
            },
        ];

        let result = validate_dag(&tasks);
        assert!(matches!(result, Err(DagGenError::InvalidDag(_))));
        if let Err(DagGenError::InvalidDag(msg)) = result {
            assert!(msg.contains("depends on itself"));
        }
    }
}
